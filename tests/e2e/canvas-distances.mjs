// node tests/e2e/canvas-distances.mjs http://127.0.0.1:5186
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.setDefaultTimeout(10000)
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.route('https://**/*', r => r.abort())
  await page.goto(process.argv[2] || 'http://127.0.0.1:5186')
  await page.locator('.canvas-stage').waitFor()
  await page.waitForTimeout(1000)
  await page.locator('input[type=file][accept="image/svg+xml,.svg"]').setInputFiles({name:'distances.svg', mimeType:'image/svg+xml', buffer:Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 300"><rect id="background" width="400" height="300" fill="#ddd"/><g id="group"><rect id="a" x="40" y="40" width="60" height="40" fill="red"/><rect id="b" x="140" y="40" width="60" height="40" fill="blue"/></g><rect id="c" x="40" y="160" width="60" height="40" fill="green"/><rect id="d" x="250" y="160" width="60" height="40" fill="purple"/></svg>')})
  const node = id => page.locator(`.svg-wrap #${id}`)
  const settle = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(() => requestAnimationFrame(resolve)))))
  const labels = async expected => {
    await settle()
    assert.deepEqual((await page.locator('.layer-distance-label').allTextContents()).map(Number).sort((a,b)=>a-b), expected.sort((a,b)=>a-b))
  }
  const select = async (id, modifiers=[]) => {
    const editorId = await node(id).getAttribute('data-editor-id')
    await page.locator(`.layer-row[data-layer-id="${editorId}"] .layer-name`).click({modifiers})
    await settle()
  }
  await select('a')
  const before = await page.locator('.svg-wrap').innerHTML()
  await node('b').hover()
  await labels([])
  await page.keyboard.down('Alt')
  await labels([40])
  await node('c').hover()
  await labels([80])
  await page.screenshot({path:'/tmp/vecsy-distances.png'})
  await node('d').hover()
  await labels([150,80])
  await page.keyboard.up('Alt')
  await labels([])
  await page.getByRole('button',{name:/Zoom in|放大/}).first().click()
  await page.keyboard.down('Alt')
  await node('b').hover()
  await labels([40])
  await page.locator('.canvas-toolbar').hover()
  await labels([])
  await node('background').hover({position:{x:10,y:10}})
  await labels([40,300,40,220])
  await page.keyboard.up('Alt')
  await select('group')
  await page.keyboard.down('Alt')
  await node('d').hover()
  await labels([50,80])
  await page.keyboard.up('Alt')
  await select('a')
  await select('b',['Shift'])
  await page.keyboard.down('Alt')
  await node('d').hover()
  await labels([50,80])
  assert.equal(await page.locator('.layer-row.selected').count(),2)
  await page.keyboard.up('Alt')
  await page.keyboard.press('h')
  await page.keyboard.down('Alt')
  await node('d').hover()
  await labels([])
  await page.keyboard.up('Alt')
  await page.keyboard.press('v')
  await node('d').hover()
  await page.keyboard.down('Alt')
  await labels([50,80])
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await labels([])
  await page.keyboard.up('Alt')
  assert.equal(await page.locator('.svg-wrap').innerHTML(),before,'measurement never edits markup')
  assert.deepEqual(errors,[])
  console.log('Distance E2E passed: Option, horizontal/vertical/diagonal, containment, zoom, group, multi-selection, leave, release, pan, blur; no page errors')
} finally { await browser.close() }
