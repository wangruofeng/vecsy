// Run against a local dev server: node tests/e2e/canvas-selection.mjs http://127.0.0.1:5178
import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('https://**/*', route => route.abort())
  await page.goto(process.argv[2] || 'http://127.0.0.1:5178')
  await page.locator('.canvas-stage').waitFor()
  await page.waitForTimeout(1000)
  await page.locator('input[type=file][accept="image/svg+xml,.svg"]').setInputFiles({ name: 'marquee.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 300"><rect id="first" x="50" y="50" width="40" height="40" fill="red"/><rect id="second" x="150" y="50" width="40" height="40" fill="blue"/><rect id="third" x="280" y="180" width="40" height="40" fill="green"/></svg>') })
  await page.locator('.svg-wrap #third').waitFor()
  const selected = () => page.locator('.layer-row.selected').count()
  const drag = async (a,b) => { await page.mouse.move(a.x,a.y); await page.mouse.down(); await page.mouse.move(b.x,b.y,{steps:10}); await page.mouse.up() }
  const bounds = async () => {
    const a = await page.locator('.svg-wrap #first').boundingBox()
    const b = await page.locator('.svg-wrap #second').boundingBox()
    return { start:{x:a.x-10,y:a.y-10}, end:{x:b.x+b.width+10,y:b.y+b.height+10} }
  }
  let box = await bounds()
  await drag(box.start,box.end)
  assert.equal(await selected(),2,'marquee selects two layers')
  await page.keyboard.down('Shift')
  await page.locator('.svg-wrap #third').click({ modifiers: ['Shift'] })
  await page.keyboard.up('Shift')
  await page.waitForFunction(() => document.querySelectorAll('.layer-row.selected').length === 3)
  assert.equal(await selected(),3,'Shift adds layer')
  await page.keyboard.down('Shift')
  await page.locator('.svg-wrap #third').click({ modifiers: ['Shift'] })
  await page.keyboard.up('Shift')
  assert.equal(await selected(),2,'Shift removes layer')
  const before = await page.locator('.svg-wrap').innerHTML()
  await page.locator('.canvas-mode-tools button').nth(1).click()
  const a = await page.locator('.svg-wrap #first').boundingBox()
  await drag({x:a.x+10,y:a.y+10},{x:a.x+40,y:a.y+30})
  assert.equal(await page.locator('.svg-wrap').innerHTML(),before,'pan leaves SVG unchanged')
  assert.equal(await selected(),2,'pan preserves selection')
  const moved = await page.locator('.svg-wrap #first').boundingBox()
  assert.ok(Math.abs(moved.x-a.x-30)<1,'pan changes viewport')
  await page.locator('.canvas-mode-tools button').first().click()
  box=await bounds()
  await page.mouse.move(box.start.x,box.start.y); await page.mouse.down()
  await page.mouse.move(box.end.x,box.end.y,{steps:10})
  assert.equal(await page.locator('.canvas-marquee').count(),1)
  await page.keyboard.press('Escape'); await page.mouse.up()
  assert.equal(await selected(),2,'Escape preserves pre-marquee selection')
  assert.equal(await page.locator('.canvas-marquee').count(),0)
  await page.getByRole('button',{name:/Zoom in|放大/,exact:false}).first().click()
  box=await bounds(); await drag(box.end,box.start)
  assert.equal(await selected(),2,'reverse marquee works after zoom and pan')
  const beforeMove = await page.locator('.svg-wrap #first').getAttribute('transform')
  const first = await page.locator('.svg-wrap #first').boundingBox()
  const second = await page.locator('.svg-wrap #second').boundingBox()
  await drag({x:first.x+20,y:first.y+20},{x:first.x+40,y:first.y+30})
  const afterFirst = await page.locator('.svg-wrap #first').boundingBox()
  const afterSecond = await page.locator('.svg-wrap #second').boundingBox()
  assert.ok(Math.abs(afterFirst.x-first.x-20)<1)
  assert.ok(Math.abs(afterSecond.x-second.x-20)<1,'both selected layers move together')
  await page.keyboard.press('Control+z')
  assert.equal(await page.locator('.svg-wrap #first').getAttribute('transform'),beforeMove,'one undo restores SVG')
  assert.equal(await selected(),2,'undo restores multi-selection')
  const third = await page.locator('.svg-wrap #third').boundingBox()
  await page.keyboard.down('Shift')
  await drag({x:third.x-8,y:third.y-8},{x:third.x+third.width+8,y:third.y+third.height+8})
  await page.keyboard.up('Shift')
  assert.equal(await selected(),3,'Shift marquee appends selection')
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await page.screenshot({path:'/tmp/vecsy-canvas-selection.png'})
  box=await bounds()
  await page.mouse.click(box.start.x,box.start.y)
  assert.equal(await selected(),0,'blank click clears selection')
  assert.deepEqual(errors,[])
  console.log('Canvas selection E2E passed: marquee, Shift toggle, pan, Escape, transformed viewport; no page errors')
} finally { await browser.close() }
